"""Configuration validation and init command for xpyd-acc.

Provides:
- generate_starter_config(): produces a well-commented TOML starter file
- validate_config(): checks a TOML file for unknown keys and type mismatches
"""

from __future__ import annotations

import sys

if sys.version_info >= (3, 11):
    import tomllib
else:
    try:
        import tomllib
    except ModuleNotFoundError:
        import tomli as tomllib  # type: ignore[no-redef]

from dataclasses import fields
from pathlib import Path
from typing import Any

from xpyd_acc.config import (
    BatchConfig,
    DefaultsConfig,
    KVConfig,
    MatchingConfig,
    ReportConfig,
)

# Map of known TOML sections to their dataclass types
_SECTION_MAP: dict[str, type] = {
    "defaults": DefaultsConfig,
    "batch": BatchConfig,
    "kv": KVConfig,
    "report": ReportConfig,
    "matching": MatchingConfig,
    "profiles": dict,  # special: profiles are free-form
}

# Python type to TOML type name for error messages
_TYPE_NAMES: dict[type, str] = {
    str: "string",
    int: "integer",
    float: "number",
    bool: "boolean",
}


