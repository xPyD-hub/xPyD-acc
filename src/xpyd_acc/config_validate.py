# Generated by: xpyd-acc init
# Docs: https://github.com/xPyD-hub/xPyD-acc

[defaults]
# baseline = "http://localhost:8000/v1"
# target = "http://localhost:8001/v1"
# model = "default"
# api_key = "no-key"
# max_tokens = 64
# retries = 3
# retry_delay = 1.0
# temperature = 0.0
